using System.Threading;
using System.Threading.Tasks;
using Tum.Quantum.Core.Models;

namespace Tum.Quantum.Core.Interfaces
{
    /// <summary>
    /// Post-Quantum TLS 1.3 Handshake Engine compliant with RFC 8446 and IETF hybrid key exchange draft.
    /// Provides client-side and server-side key encapsulation, HKDF schedule derivation, and traffic key isolation.
    /// </summary>
    public interface IPqcTls13HandshakeEngine
    {
        /// <summary>
        /// Generates a client-side ClientHello with an ephemeral composite post-quantum key share.
        /// </summary>
        /// <param name="group">The preferred post-quantum or hybrid named group.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>A fully initialized ClientHello with ephemeral key shares.</returns>
        Task<PqcTlsClientHello> GenerateClientHelloAsync(PqcTlsNamedGroup group = PqcTlsNamedGroup.X25519MLKEM768, CancellationToken cancellationToken = default);

        /// <summary>
        /// Server processes the ClientHello, encapsulates an ML-KEM shared secret, and produces a ServerHello.
        /// </summary>
        /// <param name="clientHello">The incoming ClientHello.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>The ServerHello response with encapsulated key share.</returns>
        Task<PqcTlsServerHello> ProcessClientHelloAsync(PqcTlsClientHello clientHello, CancellationToken cancellationToken = default);

        /// <summary>
        /// Finalizes the client-side handshake, decapsulates the server share, and computes the TLS 1.3 traffic keys.
        /// </summary>
        /// <param name="clientHello">The original ClientHello with ephemeral secrets.</param>
        /// <param name="serverHello">The received ServerHello response.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>The handshake completion result with derived traffic keys.</returns>
        Task<PqcTlsHandshakeResult> FinalizeClientHandshakeAsync(PqcTlsClientHello clientHello, PqcTlsServerHello serverHello, CancellationToken cancellationToken = default);

        /// <summary>
        /// Finalizes the server-side handshake and computes matching application traffic keys.
        /// </summary>
        /// <param name="clientHello">The original ClientHello.</param>
        /// <param name="serverHello">The ServerHello generated by this server.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        /// <returns>The handshake completion result from the server perspective.</returns>
        Task<PqcTlsHandshakeResult> FinalizeServerHandshakeAsync(PqcTlsClientHello clientHello, PqcTlsServerHello serverHello, CancellationToken cancellationToken = default);
    }
}
